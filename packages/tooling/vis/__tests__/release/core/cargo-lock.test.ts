import { realpathSync } from "node:fs";
import { mkdir, mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { cargoManifestPaths, findCargoLock, rewriteCargoLockVersion, syncCargoLocks } from "../../../src/release/core/cargo-lock";

/**
 * Coverage for Cargo.lock sync. Only the workspace-member block (no `source`)
 * named after the crate changes; registry and git dependencies keep their
 * versions even when the names collide.
 */

const LOCK = [
    "# This file is automatically @generated by Cargo.",
    "version = 4",
    "",
    "[[package]]",
    "name = \"app\"",
    "version = \"0.1.0\"",
    "dependencies = [",
    " \"serde\",",
    "]",
    "",
    "[[package]]",
    "name = \"serde\"",
    "version = \"1.0.200\"",
    "source = \"registry+https://github.com/rust-lang/crates.io-index\"",
    "",
    "[[package]]",
    "name = \"helper\"",
    "version = \"0.1.0\"",
    "",
].join("\n");

describe("cargo-lock: rewriteCargoLockVersion", () => {
    it("bumps only the workspace-member block", () => {
        expect.hasAssertions();

        const result = rewriteCargoLockVersion(LOCK, "app", "0.2.0");

        expect(result.found).toBe(true);
        expect(result.content).toBe(LOCK.replace("name = \"app\"\nversion = \"0.1.0\"", "name = \"app\"\nversion = \"0.2.0\""));
    });

    it("never rewrites a registry dependency that shares the crate name", () => {
        expect.hasAssertions();

        const lock = [
            "[[package]]",
            "name = \"serde\"",
            "version = \"1.0.200\"",
            "source = \"registry+https://github.com/rust-lang/crates.io-index\"",
            "",
        ].join("\n");

        expect(rewriteCargoLockVersion(lock, "serde", "9.9.9")).toStrictEqual({ found: false });
    });

    it("reports not found when the crate is absent from the lockfile", () => {
        expect.hasAssertions();

        expect(rewriteCargoLockVersion(LOCK, "missing", "1.0.0")).toStrictEqual({ found: false });
    });

    it("preserves CRLF line endings", () => {
        expect.hasAssertions();

        const lock = "[[package]]\r\nname = \"app\"\r\nversion = \"0.1.0\"\r\n";

        expect(rewriteCargoLockVersion(lock, "app", "0.2.0").content).toBe("[[package]]\r\nname = \"app\"\r\nversion = \"0.2.0\"\r\n");
    });
});

describe("cargo-lock: findCargoLock and sync", () => {
    let root: string;

    beforeEach(async () => {
        root = realpathSync.native(await mkdtemp(join(tmpdir(), "vis-cargo-lock-")));
        await mkdir(join(root, "crates", "app"), { recursive: true });
        await writeFile(join(root, "Cargo.lock"), LOCK);
        await writeFile(join(root, "crates", "app", "Cargo.toml"), "[package]\nname = \"app\"\nversion = \"0.1.0\"\n");
    });

    afterEach(async () => {
        await rm(root, { force: true, recursive: true });
    });

    it("finds the workspace-root lockfile from a member directory", async () => {
        expect.hasAssertions();

        await expect(findCargoLock(join(root, "crates", "app"), root)).resolves.toBe(join(root, "Cargo.lock"));
    });

    it("does not walk above the workspace root", async () => {
        expect.hasAssertions();

        await mkdir(join(root, "inner"), { recursive: true });

        await expect(findCargoLock(join(root, "inner"), join(root, "inner"))).resolves.toBeUndefined();
    });

    it("syncs the lockfile for a crate manifest", async () => {
        expect.hasAssertions();

        const result = await syncCargoLocks({
            entries: [
                { manifestPath: join(root, "crates", "app", "Cargo.toml"), newVersion: "0.2.0" },
            ],
            pending: new Map(),
            workspaceRoot: root,
        });

        expect(result.warnings).toStrictEqual([]);
        expect(result.writes).toStrictEqual([{ content: LOCK.replace("name = \"app\"\nversion = \"0.1.0\"", "name = \"app\"\nversion = \"0.2.0\""), path: join(root, "Cargo.lock") }]);
    });

    it("warns when the crate has no lockfile entry", async () => {
        expect.hasAssertions();

        await writeFile(join(root, "crates", "app", "Cargo.toml"), "[package]\nname = \"unlisted\"\nversion = \"0.1.0\"\n");

        const result = await syncCargoLocks({
            entries: [
                { manifestPath: join(root, "crates", "app", "Cargo.toml"), newVersion: "0.2.0" },
            ],
            pending: new Map(),
            workspaceRoot: root,
        });

        expect(result.writes).toStrictEqual([]);
        expect(result.warnings).toHaveLength(1);
    });

    it("chains two crates in one workspace through the pending map", async () => {
        expect.hasAssertions();

        await mkdir(join(root, "crates", "helper"), { recursive: true });
        await writeFile(join(root, "crates", "helper", "Cargo.toml"), "[package]\nname = \"helper\"\nversion = \"0.1.0\"\n");

        const pending = new Map<string, string>();
        const result = await syncCargoLocks({
            entries: [
                { manifestPath: join(root, "crates", "app", "Cargo.toml"), newVersion: "0.2.0" },
                { manifestPath: join(root, "crates", "helper", "Cargo.toml"), newVersion: "0.2.0" },
            ],
            pending,
            workspaceRoot: root,
        });

        expect(result.writes).toHaveLength(1);
        expect(result.writes[0]!.content).toContain("name = \"app\"\nversion = \"0.2.0\"");
        expect(result.writes[0]!.content).toContain("name = \"helper\"\nversion = \"0.2.0\"");
        await expect(readFile(join(root, "Cargo.lock"), "utf8")).resolves.toBe(LOCK);
    });

    it("lists the cargo manifests a package bumps", () => {
        expect.hasAssertions();

        expect(cargoManifestPaths("pkg", { cargoTomlPath: "crate/Cargo.toml", versionActions: "cargo" })).toStrictEqual([join("pkg", "crate", "Cargo.toml")]);
        expect(cargoManifestPaths("pkg", { versionFiles: ["src-tauri/Cargo.toml", "tauri.conf.json"] })).toStrictEqual([
            join("pkg", "src-tauri", "Cargo.toml"),
        ]);
        expect(cargoManifestPaths("pkg", {})).toStrictEqual([]);
    });
});
