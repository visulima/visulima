import { mkdirSync, mkdtempSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { afterEach, beforeEach, describe, expect, it } from "vitest";

import { buildFlatSbomParts } from "../../src/sbom/flat";
import { lockedPackagesForEcosystem, swiftPackageName } from "../../src/security/multi-eco-lockfiles";

// The SBOM for these lists is flat: every component has a `dependencies` entry with no `dependsOn`.
// go.sum, pubspec.lock and Package.resolved record versions but no edges between packages.

const GO_SUM = [
    "github.com/gorilla/mux v1.8.0 h1:abc=",
    "github.com/gorilla/mux v1.8.0/go.mod h1:def=",
    "golang.org/x/net v0.1.0/go.mod h1:ghi=",
    "golang.org/x/net v0.1.0 h1:jkl=",
    "",
].join("\n");

const PUBSPEC_LOCK = [
    "# Generated by pub",
    "packages:",
    "  async:",
    "    dependency: transitive",
    "    description:",
    "      name: async",
    "      sha256: \"aaa\"",
    "      url: \"https://pub.dev\"",
    "    source: hosted",
    "    version: \"2.11.0\"",
    "  http:",
    "    dependency: \"direct main\"",
    "    description:",
    "      name: http",
    "      url: \"https://pub.dev\"",
    "    source: hosted",
    "    version: \"0.12.0\"",
    "  test:",
    "    dependency: \"direct dev\"",
    "    description:",
    "      name: test",
    "      url: \"https://pub.dev\"",
    "    source: hosted",
    "    version: \"1.25.0\"",
    "  flutter:",
    "    dependency: \"direct main\"",
    "    description: flutter",
    "    source: sdk",
    "    version: \"0.0.0\"",
    "  local_pkg:",
    "    dependency: \"direct main\"",
    "    description:",
    "      path: \"../local_pkg\"",
    "    source: path",
    "    version: \"1.0.0\"",
    "sdks:",
    "  dart: \">=3.0.0 <4.0.0\"",
    "",
].join("\n");

const PACKAGE_RESOLVED_V3 = JSON.stringify({
    originHash: "abc",
    pins: [
        { identity: "swift-nio", kind: "remoteSourceControl", location: "https://github.com/apple/swift-nio.git", state: { revision: "r1", version: "2.65.0" } },
        { identity: "branchy", kind: "remoteSourceControl", location: "git@github.com:acme/branchy.git", state: { branch: "main", revision: "r2" } },
    ],
    version: 3,
});

const PACKAGE_RESOLVED_V2 = JSON.stringify({
    pins: [{ identity: "vapor", kind: "remoteSourceControl", location: "https://github.com/vapor/vapor", state: { revision: "r3", version: "4.89.0" } }],
    version: 2,
});

describe("flat lock SBOM (go.sum, pubspec.lock, Package.resolved)", () => {
    let root: string;

    beforeEach(() => {
        root = realpathSync(mkdtempSync(join(tmpdir(), "vis-flat-lock-")));
        mkdirSync(root, { recursive: true });
    });

    afterEach(() => {
        rmSync(root, { force: true, recursive: true });
    });

    it("reads go.sum module versions, skipping the go.mod hash lines", () => {
        expect.hasAssertions();

        writeFileSync(join(root, "go.sum"), GO_SUM);

        expect(lockedPackagesForEcosystem(root, "Go")).toStrictEqual([
            { isDev: false, name: "github.com/gorilla/mux", version: "v1.8.0" },
            { isDev: false, name: "golang.org/x/net", version: "v0.1.0" },
        ]);
    });

    it("reads only hosted pubspec.lock entries", () => {
        expect.hasAssertions();

        writeFileSync(join(root, "pubspec.lock"), PUBSPEC_LOCK);

        expect(lockedPackagesForEcosystem(root, "Pub")).toStrictEqual([
            { isDev: false, name: "async", version: "2.11.0" },
            { isDev: false, name: "http", version: "0.12.0" },
            { isDev: true, name: "test", version: "1.25.0" },
        ]);
    });

    it("reads Package.resolved v2 and v3 pins, skipping pins with no version", () => {
        expect.hasAssertions();

        writeFileSync(join(root, "Package.resolved"), PACKAGE_RESOLVED_V3);

        expect(lockedPackagesForEcosystem(root, "SwiftURL")).toStrictEqual([{ isDev: false, name: "github.com/apple/swift-nio", version: "2.65.0" }]);

        writeFileSync(join(root, "Package.resolved"), PACKAGE_RESOLVED_V2);

        expect(lockedPackagesForEcosystem(root, "SwiftURL")).toStrictEqual([{ isDev: false, name: "github.com/vapor/vapor", version: "4.89.0" }]);
    });

    it("normalizes Swift locations to OSV's host/owner/repo name", () => {
        expect.hasAssertions();

        expect(swiftPackageName("https://github.com/apple/swift-nio.git")).toBe("github.com/apple/swift-nio");
        expect(swiftPackageName("git@github.com:acme/branchy.git")).toBe("github.com/acme/branchy");
    });

    it("builds purls with no dependsOn for every component", () => {
        expect.hasAssertions();

        writeFileSync(join(root, "go.sum"), GO_SUM);
        writeFileSync(join(root, "pubspec.lock"), PUBSPEC_LOCK);
        writeFileSync(join(root, "Package.resolved"), PACKAGE_RESOLVED_V3);

        const go = buildFlatSbomParts(root, "Go");
        const pub = buildFlatSbomParts(root, "Pub");
        const swift = buildFlatSbomParts(root, "SwiftURL");

        expect(go.components.map((component) => component.purl)).toStrictEqual(["pkg:golang/github.com/gorilla/mux@v1.8.0", "pkg:golang/golang.org/x/net@v0.1.0"]);
        expect(pub.components.map((component) => component.purl)).toStrictEqual(["pkg:pub/async@2.11.0", "pkg:pub/http@0.12.0", "pkg:pub/test@1.25.0"]);
        expect(swift.components.map((component) => component.purl)).toStrictEqual(["pkg:swift/github.com/apple/swift-nio@2.65.0"]);

        // Flat: one dependency entry per component, and none of them claims an edge.
        for (const part of [go, pub, swift]) {
            expect(part.dependencies).toStrictEqual(part.components.map((component) => { return { ref: component.purl }; }));
            expect(part.dependencies.every((dependency) => dependency.dependsOn === undefined)).toBe(true);
        }
    });

    it("returns nothing without a lockfile", () => {
        expect.hasAssertions();

        expect(buildFlatSbomParts(root, "Go")).toStrictEqual({ components: [], dependencies: [] });
        expect(buildFlatSbomParts(root, "Pub")).toStrictEqual({ components: [], dependencies: [] });
        expect(buildFlatSbomParts(root, "SwiftURL")).toStrictEqual({ components: [], dependencies: [] });
    });
});
